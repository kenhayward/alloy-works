import { PLURAL_RULE_OF, PLURAL_RULES } from './plural-rules.js';

/**
 * **A value's plural category** (the MF plan, MF-B): CLDR's cardinal rules, compiled by
 * `generate:languages` into `plural-rules.ts` and read here, so the editor and the worker select alike
 * with no platform `Intl`. Held to the interface's FormatJS by `apps/web`'s plural-parity test.
 */

export const PLURAL_CATEGORIES = ['zero', 'one', 'two', 'few', 'many', 'other'] as const;
export type PluralCategory = (typeof PLURAL_CATEGORIES)[number];

/** CLDR's operands (TR35, "Plural Operand Meanings"); `e` and `c` are always 0 here. */
export type PluralOperand = 'n' | 'i' | 'v' | 'w' | 'f' | 't' | 'e' | 'c';

/** `operand % mod` (0: none) in one of the inclusive ranges, `[from, to, from, to, ...]`; or not. */
export type PluralRelation =
  | readonly [PluralOperand, number, readonly number[]]
  | readonly [PluralOperand, number, readonly number[], true];

/** Relations ANDed within a list, the lists ORed. */
export type PluralCondition = readonly (readonly PluralRelation[])[];

/** A locale's rules in CLDR's order, `other` left out: what nothing else matches. */
export type PluralRuleSet = readonly (readonly [PluralCategory, PluralCondition])[];

export interface CompiledPluralRules {
  /** Each distinct rule set once. */
  readonly rules: readonly PluralRuleSet[];
  /** CLDR's locale key to its rule set's index. */
  readonly of: Readonly<Record<string, number>>;
}

const PREFIX = 'pluralRule-count-';
const RELATION =
  /^([nivwftec])(?:\s*%\s*(\d+))?\s*(!=|=)\s*(\d+(?:\.\.\d+)?(?:,\d+(?:\.\.\d+)?)*)$/;

function relation(text: string): PluralRelation {
  const match = RELATION.exec(text.trim());
  if (!match) throw new Error(`A plural relation CLDR's syntax does not allow: ${text}`);
  const [, operand, mod, op, list] = match;
  const ranges = list!.split(',').flatMap((each) => {
    const [from, to = from] = each.split('..');
    return [Number(from), Number(to)];
  });
  const head = [operand as PluralOperand, mod === undefined ? 0 : Number(mod), ranges] as const;
  return op === '!=' ? [...head, true] : head;
}

/** A rule's condition, its samples set aside; empty for `other`'s. */
function condition(rule: string): PluralCondition {
  const text = rule.split('@')[0]!.trim();
  if (text === '') return [];
  return text.split(/\s+or\s+/).map((and) => and.split(/\s+and\s+/).map(relation));
}

/** CLDR's `plurals-type-cardinal` compiled, each distinct rule set once, in CLDR's key order. */
export function compilePluralRules(
  cldr: Readonly<Record<string, Readonly<Record<string, string>>>>,
): CompiledPluralRules {
  const rules: PluralRuleSet[] = [];
  const seen = new Map<string, number>();
  const of: Record<string, number> = {};
  for (const [locale, each] of Object.entries(cldr)) {
    const set: PluralRuleSet = Object.entries(each)
      .map(([key, rule]) => [key.replace(PREFIX, '') as PluralCategory, rule] as const)
      .filter(([category]) => category !== 'other')
      .map(([category, rule]) => {
        if (!PLURAL_CATEGORIES.includes(category)) throw new Error(`Not a category: ${category}`);
        return [category, condition(rule)] as const;
      });
    const key = JSON.stringify(set);
    let index = seen.get(key);
    if (index === undefined) {
      index = rules.push(set) - 1;
      seen.set(key, index);
    }
    of[locale] = index;
  }
  return { rules, of };
}

/** plural-rules.ts as the generator writes it. */
export function renderPluralRules(compiled: CompiledPluralRules): string {
  return `// Generated by \`pnpm --filter @alloy-works/domain generate:languages\` from the pinned CLDR's cardinal
// plural rules (CONTENT_LANGUAGES_CLDR): never edited by hand. plurals.test.ts regenerates and compares it.

import type { PluralRuleSet } from './plurals.js';

/** Each distinct cardinal rule set, compiled (the MF plan, MF-B). */
export const PLURAL_RULES: readonly PluralRuleSet[] = ${JSON.stringify(compiled.rules)};

/** CLDR's locale key to its rule set in \`PLURAL_RULES\`. */
export const PLURAL_RULE_OF: Readonly<Record<string, number>> = ${JSON.stringify(compiled.of)};
`;
}

/** A sample CLDR writes, as a canonical value and the scale it is printed at. */
export interface PluralSample {
  readonly value: string;
  readonly scale: number;
}

const places = (value: string) => value.split('.')[1]?.length ?? 0;

/**
 * Every `@integer` and `@decimal` sample a rule writes, `~` ranges expanded at the places their ends
 * have; the ellipsis and compact samples (`1c6`), which a canonical value cannot be, dropped.
 */
export function pluralSamples(rule: string): PluralSample[] {
  const samples: PluralSample[] = [];
  for (const section of rule.split('@').slice(1)) {
    const items = section.replace(/^(integer|decimal)/, '').split(',');
    for (const raw of items) {
      const item = raw.trim();
      if (item === '' || item === '…' || /[ce]/.test(item)) continue;
      const [from, to = from] = item.split('~') as [string, string?];
      const scale = places(from);
      const unit = (text: string) => BigInt(text.replace('.', ''));
      for (let at = unit(from); at <= unit(to!); at += 1n) {
        const digits = at.toString().padStart(scale + 1, '0');
        const value = scale === 0 ? digits : `${digits.slice(0, -scale)}.${digits.slice(-scale)}`;
        samples.push({ value, scale });
      }
    }
  }
  return samples;
}

type Operands = Readonly<Record<PluralOperand, bigint | undefined>>;

const CANONICAL = /^-?\d+(?:\.\d+)?$/;

/** The operands of a canonical value printed at `scale` places; `n` only where it is whole. */
function operandsOf(value: string, scale: number): Operands {
  if (!CANONICAL.test(value) || !Number.isInteger(scale) || scale < 0) {
    throw new Error(`Not a canonical number at a scale: ${value}, ${scale}`);
  }
  const [whole, fraction = ''] = value.replace(/^-/, '').split('.') as [string, string?];
  const visible = fraction!.padEnd(scale, '0');
  const trimmed = visible.replace(/0+$/, '');
  const i = BigInt(whole);
  const f = BigInt(visible || '0');
  return {
    // Whole, `n` is `i`; with a fraction it equals no integer, which every rule compares it with.
    n: f === 0n ? i : undefined,
    i,
    v: BigInt(visible.length),
    w: BigInt(trimmed.length),
    f,
    t: BigInt(trimmed || '0'),
    e: 0n,
    c: 0n,
  };
}

function holds(o: Operands, [operand, mod, ranges, negated]: PluralRelation): boolean {
  const x = o[operand];
  let found = false;
  if (x !== undefined) {
    const y = mod === 0 ? x : x % BigInt(mod);
    for (let at = 0; at < ranges.length && !found; at += 2) {
      found = y >= BigInt(ranges[at]!) && y <= BigInt(ranges[at + 1]!);
    }
  }
  return negated ? !found : found;
}

let lowered: ReadonlyMap<string, number> | undefined;

/** A language's rule set: its full tag's, else its language's, else `und`'s, in any case. */
function ruleSetOf(language: string): PluralRuleSet {
  lowered ??= new Map(
    Object.entries(PLURAL_RULE_OF).map(([key, index]) => [key.toLowerCase(), index]),
  );
  const tag = language.toLowerCase();
  const index = lowered.get(tag) ?? lowered.get(tag.split('-')[0]!) ?? lowered.get('und')!;
  return PLURAL_RULES[index]!;
}

/**
 * **The plural category of a canonical value in a language** (MF-B): operands read from the value at
 * the column's declared `scale`, so 1.50 is English's `other` as it prints, never from a float.
 */
export function pluralCategory(language: string, value: string, scale: number): PluralCategory {
  const o = operandsOf(value, scale);
  for (const [category, or] of ruleSetOf(language)) {
    if (or.some((and) => and.every((each) => holds(o, each)))) return category;
  }
  return 'other';
}

/** The categories a language uses (MF-F), in CLDR's order, `other` last. */
export function pluralCategoriesOf(language: string): PluralCategory[] {
  const used = new Set(ruleSetOf(language).map(([category]) => category));
  return PLURAL_CATEGORIES.filter((category) => category === 'other' || used.has(category));
}

/** What the examples are drawn from, in order: whole numbers, large round ones, then tenths. */
const PROBES: readonly PluralSample[] = [
  ...Array.from({ length: 201 }, (_, at) => ({ value: String(at), scale: 0 })),
  ...['1000', '10000', '100000', '1000000'].map((value) => ({ value, scale: 0 })),
  ...Array.from({ length: 21 }, (_, at) => ({ value: (at / 10).toFixed(1), scale: 1 })),
];

/**
 * **A category's first examples in a language** (MF-F), for a translator's note: the rules are compiled
 * without CLDR's samples, so these are found by the rules themselves, as `pluralCategory` selects.
 */
export function pluralExamples(language: string, category: PluralCategory, count = 3): string[] {
  return PROBES.filter((probe) => pluralCategory(language, probe.value, probe.scale) === category)
    .slice(0, count)
    .map((probe) => probe.value);
}
