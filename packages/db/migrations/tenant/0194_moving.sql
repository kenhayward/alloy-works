-- Moving content between spaces (moving.md; the MV plan). 0007 said moving is not designed; it is now.
-- Only the space changes: `artifact_space_changed` (0010) moves the access epoch, so no decision outlives it.
do $$
begin
  execute format('grant update (space_id) on artifact to %I', current_schema());
  execute format('grant update (space_id) on search_earlier to %I', current_schema());
end
$$;

-- One move, inserted and never changed: what lets a document say a part it withholds has moved (MV-F),
-- as artifact_archival records archival.
create table artifact_move (
  id bigint generated always as identity primary key,
  artifact_id uuid not null references artifact on delete restrict,
  from_space uuid not null references space on delete restrict,
  to_space uuid not null references space on delete restrict,
  by uuid not null references principal on delete restrict,
  at timestamptz not null default now()
);
create index artifact_move_artifact on artifact_move (artifact_id, id);

do $$
begin
  execute format('revoke update, delete, truncate on artifact_move from %I', current_schema());
end
$$;

