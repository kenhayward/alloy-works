-- Integrity re-verified (diagnostics.md, "Integrity"; the DG plan, DG-K): per class and item, the last
-- check, whether it held, and why not, as a code. Upserted by the worker's nightly share, each class a
-- 28th a night; an item no longer held is left behind, and not counted. Left out of exports.
create table integrity_check (
  class text not null check (class in ('asset', 'version', 'audit_export', 'tenant_export')),
  item uuid not null,
  checked_at timestamptz not null,
  ok boolean not null,
  failure text check (failure in ('hash_mismatch', 'digest_mismatch', 'object_missing')),
  primary key (class, item),
  check (ok = (failure is null))
);
create index integrity_check_due on integrity_check (class, checked_at);

