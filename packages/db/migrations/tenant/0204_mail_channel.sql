-- A tenant's mail channel (mail.md; the EM plan): how its mail leaves. At most one row; none means off.

create table mail_channel (
  id uuid primary key default gen_random_uuid(),
  singleton boolean not null default true unique check (singleton),
  enabled boolean not null default false,
  relay text not null default 'platform' check (relay in ('platform', 'own')),
  host text check (char_length(host) between 1 and 253),
  port integer check (port in (465, 587)),
  username text check (char_length(username) between 1 and 254),
  -- Sealed by the connector to this tenant, host, port and username (EM-I).
  sealed_password text,
  from_address text check (char_length(from_address) <= 254),
  from_name text check (char_length(from_name) <= 100),
  updated_at timestamptz not null default now(),
  updated_by uuid references principal (id) on delete set null,
  constraint mail_channel_own_named check (
    relay <> 'own' or (host is not null and port is not null and from_address is not null)
  ),
  constraint mail_channel_platform_names_nothing check (
    relay <> 'platform' or (
      host is null and port is null and username is null and sealed_password is null
      and from_address is null
    )
  ),
  constraint mail_channel_on_with_a_password check (
    not enabled or relay = 'platform' or username is null or sealed_password is not null
  )
);

