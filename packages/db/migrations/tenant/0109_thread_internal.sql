-- Internal threads (COL-038; the R13 plan, R13-C): a thread kept from every principal from outside
-- the tenant. Marked when it is started, or later while it is open, by somebody inside; never unmarked,
-- since a public thread would show a client what was written for colleagues. Inserted and read alone.
create table thread_internal (
  thread_id uuid primary key references thread on delete restrict,
  marked_by uuid not null references principal on delete restrict,
  marked_at timestamptz not null default now()
);

do $$
begin
  execute format('revoke update, delete, truncate on thread_internal from %I', current_schema());
end
$$;

